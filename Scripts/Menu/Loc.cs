// Two languages: English (the text in the code and scene) and Russian.
// Loc.T(text) returns the Russian version when Russian is selected, otherwise the text itself.
// Text with numbers in it ("Night 2 survived.") is looked up with the numbers replaced by {0}, {1}...
public static class Loc
{
    public static bool Ru => GameSettings.Language == 1;

    public static string T(string s)
    {
        if (!Ru || string.IsNullOrEmpty(s)) return s;
        if (cache.TryGetValue(s, out var c)) return c;
        string r;
        if (!ru.TryGetValue(s, out r)) r = Templated(s);
        if (cache.Count > 4000) cache.Clear();
        cache[s] = r;
        return r;
    }

    static readonly Dictionary<string, string> cache = new Dictionary<string, string>();
    static readonly StringBuilder sb = new StringBuilder();
    static readonly List<string> nums = new List<string>();

    static string Templated(string s)
    {
        sb.Length = 0; nums.Clear();
        int i = 0;
        while (i < s.Length)
        {
            if (char.IsDigit(s[i]))
            {
                int j = i; while (j < s.Length && char.IsDigit(s[j])) j++;
                sb.Append('{').Append(nums.Count).Append('}');
                nums.Add(s.Substring(i, j - i)); i = j;
            }
            else { sb.Append(s[i]); i++; }
        }
        if (nums.Count == 0) return s;
        if (!ru.TryGetValue(sb.ToString(), out var t)) return s;
        for (int k = 0; k < nums.Count; k++) t = t.Replace("{" + k + "}", nums[k]);
        return t;
    }

